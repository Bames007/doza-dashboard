import jsPDF from "jspdf";
import autoTable from "jspdf-autotable";
import { LabTest } from "../types/lab";

interface PDFData {
  tests: LabTest[];
  centerName: string;
  centerAddress?: string;
  centerPhone?: string;
  centerEmail?: string;
  technicianName?: string;
  sealBase64?: string;
  includeWatermark?: boolean;
}

export const generateLabReport = (data: PDFData): jsPDF => {
  const doc = new jsPDF();
  const {
    tests,
    centerName,
    centerAddress,
    centerPhone,
    centerEmail,
    technicianName,
    sealBase64,
    includeWatermark = true,
  } = data;

  if (tests.length === 0) return doc;

  // Group tests by patient
  const patientGroups = tests.reduce(
    (groups, test) => {
      const key = test.patientId;
      if (!groups[key]) {
        groups[key] = {
          patientName: test.patientName,
          patientId: test.patientId,
          tests: [],
        };
      }
      groups[key].tests.push(test);
      return groups;
    },
    {} as Record<
      string,
      { patientName: string; patientId: string; tests: LabTest[] }
    >,
  );

  // Helper to format date
  const formatDate = (dateStr: string) =>
    new Date(dateStr).toLocaleDateString("en-US", {
      year: "numeric",
      month: "short",
      day: "numeric",
    });

  // Add watermark
  if (includeWatermark) {
    doc.setFontSize(40);
    doc.setTextColor(240, 240, 240);
    doc.text("DOZA", 105, 150, { align: "center", angle: 45 });
  }

  // ========== HEADER ==========
  doc.setFontSize(20);
  doc.setTextColor(0, 100, 0); // dark green
  doc.text(centerName, 105, 20, { align: "center" });

  doc.setFontSize(10);
  doc.setTextColor(100);
  let headerY = 28;
  if (centerAddress) {
    doc.text(centerAddress, 105, headerY, { align: "center" });
    headerY += 6;
  }
  if (centerPhone || centerEmail) {
    doc.text(`${centerPhone || ""} ${centerEmail || ""}`, 105, headerY, {
      align: "center",
    });
    headerY += 6;
  }

  // Report title and generation info
  doc.setFontSize(16);
  doc.setTextColor(0);
  doc.text("Laboratory Test Report", 105, headerY + 8, { align: "center" });

  const generationDate = new Date().toLocaleString();
  doc.setFontSize(9);
  doc.setTextColor(150);
  doc.text(`Report generated: ${generationDate}`, 105, headerY + 16, {
    align: "center",
  });

  // Add technician name if provided
  if (technicianName) {
    doc.text(`Generated by: ${technicianName}`, 105, headerY + 22, {
      align: "center",
    });
  }

  let yOffset = headerY + 28;

  // ========== PATIENT SECTIONS ==========
  Object.values(patientGroups).forEach((group) => {
    // Patient header
    doc.setFontSize(14);
    doc.setTextColor(0);
    doc.text(`Patient: ${group.patientName}`, 14, yOffset);
    doc.setFontSize(10);
    doc.text(`Patient ID: ${group.patientId}`, 14, yOffset + 6);
    yOffset += 12;

    // Build test rows – use concludedByName if available
    const testRows = group.tests.map((test) => [
      test.testType,
      test.result?.value || "—",
      test.result?.unit || "—",
      test.result?.referenceRange || "—",
      test.result?.notes || "—",
      test.result?.concludedByName || test.result?.concludedBy || "—",
      formatDate(test.collectionDate),
    ]);

    // Render table
    autoTable(doc, {
      startY: yOffset,
      head: [
        [
          "Test",
          "Result",
          "Unit",
          "Reference Range",
          "Notes",
          "Performed By",
          "Date",
        ],
      ],
      body: testRows,
      theme: "grid",
      headStyles: { fillColor: [0, 100, 0], textColor: 255, fontSize: 10 },
      bodyStyles: { fontSize: 9 },
      columnStyles: {
        0: { cellWidth: 35 },
        1: { cellWidth: 25 },
        2: { cellWidth: 20 },
        3: { cellWidth: 30 },
        4: { cellWidth: 30 },
        5: { cellWidth: 25 },
        6: { cellWidth: 25 },
      },
      margin: { left: 14, right: 14 },
    });

    yOffset = (doc as any).lastAutoTable.finalY + 10;
  });

  // ========== FOOTER ==========
  const finalY =
    Math.max(yOffset, (doc as any).lastAutoTable?.finalY || 0) + 15;

  // Digital signature line
  doc.setDrawColor(0, 100, 0);
  doc.line(20, finalY, 90, finalY);

  // Technician's name in cursive‑style (italic)
  if (technicianName) {
    doc.setFont("helvetica", "italic");
    doc.setFontSize(12);
    doc.setTextColor(0, 100, 0);
    doc.text(technicianName, 20, finalY - 2);
  }

  // Printed name label
  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.setTextColor(80);
  doc.text("(Digitally signed)", 20, finalY + 5);

  // Seal (if provided)
  if (sealBase64) {
    doc.addImage(sealBase64, "PNG", 150, finalY - 15, 30, 30);
  }

  // Footer disclaimer
  doc.setDrawColor(200);
  doc.line(20, finalY + 20, 190, finalY + 20);
  doc.setFontSize(8);
  doc.setTextColor(150);
  doc.text(
    "This is an electronically generated report and is valid without a physical signature.",
    105,
    finalY + 28,
    { align: "center" },
  );

  return doc;
};
