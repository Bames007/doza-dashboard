export const getCenterRoleNavigation = (
  centerType: CenterType,
  userRole: UserRole,
): NavigationItem[] => {
  const validCenterTypes: CenterType[] = [
    "pharmacy",
    "hospital",
    "clinic",
    "medical_center",
    "diagnostic_lab",
    "dental_clinic",
    "optical_center",
    "emergency",
    "cardiac_center",
  ];

  if (!validCenterTypes.includes(centerType)) {
    logger.warn(
      { centerType, userRole },
      "Unknown center type – using fallback",
    );
    return getFallbackNavigation(centerType, userRole);
  }

  let navigation: NavigationRecord;
  switch (centerType) {
    case "pharmacy":
      navigation = pharmacyNavigation;
      break;
    case "hospital":
      navigation = hospitalNavigation;
      break;
    case "clinic":
      navigation = clinicNavigation;
      break;
    case "medical_center":
      navigation = medicalCenterNavigation;
      break;
    case "diagnostic_lab":
      navigation = diagnosticLabNavigation;
      break;
    case "dental_clinic":
      navigation = dentalClinicNavigation;
      break;
    case "optical_center":
      navigation = opticalCenterNavigation;
      break;
    case "emergency":
      navigation = emergencyNavigation;
      break;
    case "cardiac_center":
      navigation = cardiacCenterNavigation;
      break;
    default:
      return getFallbackNavigation(centerType, userRole);
  }

  const normalizedRole = normalizeRoleForCenter(userRole, centerType);
  const items = navigation[normalizedRole] || [];

  // const items = navigation[userRole] || [];
  if (items.length === 0) {
    if (navigation["nurse"] && navigation["nurse"].length > 0) {
      logger.debug({ centerType, userRole }, "Using generic nurse navigation");
      return navigation["nurse"];
    }
    logger.warn({ centerType, userRole }, "No navigation found – fallback");
    return getFallbackNavigation(centerType, userRole);
  }
  return items;
};

